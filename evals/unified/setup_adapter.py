"""Seed a disposable synthetic B-12 runtime from an evaluator-only setup fixture.

The adapter writes only what the current runtime can hold: memory text/kind/source in
the actor's namespace, `recorded_at` as the record's
`created_at` (the store clock is warped while seeding, as the comprehensive suite does),
`supersedes` as the runtime's stale marking, and goals through
GoalStore with its own statuses. Clock and provenance fields that canonical memory does
not store (event/record/validity times, reliability, locators) are listed in the report
as dropped, per the U3 protocol: they are a baseline limitation, never filled in.

Runtime ids are generated by the stores; the report maps declared fixture UUIDs to the
real ones so oracles can be translated. The report is evaluator-side data.
"""

import contextlib
import json
import os
from datetime import UTC, datetime, timedelta
from pathlib import Path, PurePosixPath

from b12.runtime import open_runtime

ALLOWED_ROOTS = ("sandbox", "actors")
OWNER = "synthetic-owner"
STORED_MEMORY_FIELDS = {"memory_id", "alias", "actor", "kind", "content", "source", "recorded_at"}
GOAL_STATUSES = {"active", "paused", "achieved", "abandoned", "failed"}


def _virtual_path(value):
    if not isinstance(value, str) or not value.startswith("/") or "\\" in value:
        raise ValueError(f"synthetic path must be absolute POSIX: {value!r}")
    path = PurePosixPath(value)
    parts = path.parts[1:]
    if (
        path.as_posix() != value
        or not parts
        or parts[0] not in ALLOWED_ROOTS
        or any(part in {"", ".", ".."} for part in parts)
    ):
        raise ValueError(f"synthetic path outside allowed roots: {value!r}")
    return parts


def _private_dirs(root, parts):
    current = root
    for part in parts:
        current = current / part
        if current.is_symlink():
            raise ValueError("synthetic filesystem contains a symlink")
        current.mkdir(mode=0o700, exist_ok=True)
    return current


def materialize_files(setup, root, *, existing_root=False):
    """Create a fresh directory tree for `synthetic_files`/`synthetic_dirs`.

    Virtual paths such as /sandbox/c22/in/m1.txt map to <root>/sandbox/c22/in/m1.txt.
    Returns {virtual path: real path}. `missing_files` are deliberately not created.
    """
    files = setup.get("synthetic_files", {}) or {}
    dirs = setup.get("synthetic_dirs", []) or []
    planned = {path: _virtual_path(path) for path in [*files, *dirs]}
    root = Path(root)
    if existing_root:
        # Inside the bubblewrap worker the roots are fresh tmpfs mounts at /sandbox, /actors.
        for name in ALLOWED_ROOTS:
            mount = root / name
            if mount.is_symlink() or (mount.exists() and any(mount.iterdir())):
                raise FileExistsError(f"{mount} is not an empty synthetic root")
    else:
        root.mkdir(mode=0o700, parents=True, exist_ok=False)
    result = {}
    for virtual in dirs:
        result[virtual] = _private_dirs(root, planned[virtual])
    for virtual, content in files.items():
        parts = planned[virtual]
        parent = _private_dirs(root, parts[:-1])
        target = parent / parts[-1]
        fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            output.write(content)
        result[virtual] = target
    return result


def _actors(runtime, setup):
    names = list(
        dict.fromkeys(
            [*(setup.get("synthetic_actors") or []), OWNER, setup.get("speaking_actor", OWNER)]
        )
    )
    return {name: runtime.control.create_actor(owner=name == OWNER, consent=True) for name in names}


@contextlib.contextmanager
def _store_clock(stamp):
    """Temporarily make MemoryStore stamp `created_at` with `stamp` (converted to UTC)."""
    import b12.memory as memory_module

    real_now = memory_module._now
    if stamp:
        utc = datetime.fromisoformat(stamp).astimezone(UTC).isoformat()
        memory_module._now = lambda: utc
    try:
        yield
    finally:
        memory_module._now = real_now


TEMPORAL_FIELDS = ("event_time", "valid_from", "valid_to", "reliability", "source_locator")
DOCUMENT_SOURCES = ("datasheet", "bom", "schematic", "log", "spec", "plan", "doc", "rules")


def _temporal_seed(row):
    """ADR-015 fields for a fixture row (schema v3); the origin is the owner or a document."""
    values = {k: row[k] for k in TEMPORAL_FIELDS if row.get(k)}
    if values:
        source = str(row.get("source", "")).lower()
        values["temporal_source"] = (
            "document" if any(word in source for word in DOCUMENT_SOURCES) else "owner"
        )
    return values


def _seed_memory(runtime, setup, actors, report, temporal=False):
    rows = setup.get("synthetic_memory", []) or []
    by_alias = {}
    stored = STORED_MEMORY_FIELDS | (set(TEMPORAL_FIELDS) if temporal else set())
    for row in rows:
        actor = actors[row["actor"]]
        with _store_clock(row.get("recorded_at")):
            record = runtime.memory.remember(
                row["content"],
                actor,
                kind=row["kind"],
                source=row["source"],
                **(_temporal_seed(row) if temporal else {}),
            )
        report["memory_ids"][row["memory_id"]] = record.id
        by_alias[row["alias"]] = (row, record.id, actor)
        dropped = sorted(k for k, v in row.items() if k not in stored and v)
        if dropped:
            report["dropped_fields"][row["alias"]] = dropped
    declared_to_alias = {row["memory_id"]: row["alias"] for row in rows}
    for row in rows:
        old = row.get("supersedes")
        if not old:
            continue
        old_alias = declared_to_alias[old]
        _, old_id, actor = by_alias[old_alias]
        new_id = by_alias[row["alias"]][1]
        replaced_by = new_id if temporal else None
        if not runtime.memory.supersede(old_id, actor, replaced_by=replaced_by):
            raise ValueError(f"cannot supersede {old_alias}")
        report["applied_relations"].append({"supersedes": old_alias, "by": row["alias"]})


def _seed_goals(runtime, setup, actors, sessions, report):
    for goal in setup.get("synthetic_goals", []) or []:
        status = goal["status"]
        if status not in GOAL_STATUSES:
            raise ValueError(f"unsupported goal status {status!r}")
        actor = actors[goal["actor"]]
        created = runtime.goals.create(
            actor.id, sessions[goal["actor"]], goal["text"], goal["text"]
        )
        goal_id = created["id"]
        report["goal_ids"][goal["goal_id"]] = goal_id
        if goal.get("checkpoint"):
            runtime.goals.checkpoint(
                goal_id, actor.id, goal["checkpoint"], datetime.now(UTC) + timedelta(hours=1)
            )
        evidence = [report["memory_ids"][e] for e in goal.get("evidence_ids", [])]
        if status == "achieved":
            runtime.goals.complete(
                goal_id, actor, evidence, lambda e, a=actor: runtime.memory.is_live(e, a)
            )
        elif status != "active":
            runtime.goals.set_status(
                goal_id, actor.id, status, goal.get("status_reason") or "synthetic fixture"
            )


def build_runtime(
    setup, state_dir, settings, *, files_root=None, existing_files_root=False, temporal=False
):
    """Open a fresh runtime at `state_dir`, seed actors, memory and goals, then close it.

    Returns a JSON-serializable report with real actor/session/memory/goal ids.
    """
    state_dir = Path(state_dir)
    if state_dir.exists():
        raise FileExistsError("runtime state directory already exists")
    report = {
        "actors": {},
        "sessions": {},
        "memory_ids": {},
        "goal_ids": {},
        "dropped_fields": {},
        "applied_relations": [],
        "files": {},
        "speaking_actor": setup.get("speaking_actor", OWNER),
    }
    if files_root is not None:
        written = materialize_files(setup, files_root, existing_root=existing_files_root)
        report["files"] = {k: str(v) for k, v in written.items()}
    state_dir.mkdir(mode=0o700, parents=True)
    runtime = open_runtime(
        settings.model_copy(
            update={
                "state_dir": state_dir,
                "host_access": "none",
                "memory_enrichment": False,
                "embedding_python": None,
            }
        )
    )
    try:
        actors = _actors(runtime, setup)
        sessions = {
            name: runtime.control.create_session(actor.id) for name, actor in actors.items()
        }
        report["actors"] = {name: actor.id for name, actor in actors.items()}
        report["sessions"] = dict(sessions)
        _seed_memory(runtime, setup, actors, report, temporal=temporal)
        _seed_goals(runtime, setup, actors, sessions, report)
    finally:
        runtime.close()
    json.dumps(report)  # must stay serializable for the evaluator record
    return report
