"""Generate native, manuscript-font vector figures from bundled evidence.

No model, private traces, plotting fonts or network access are required.
Compile manuscript.tex with Tectonic after running this script.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
FIG = ROOT / "figures"
FIG.mkdir(exist_ok=True)

STYLE = r"""\begin{tikzpicture}[
  box/.style={draw=inkmuted, rounded corners=1pt, line width=.5pt,
    text width=3.2cm, minimum height=9mm, align=center, inner sep=3pt,
    font=\small},
  flow/.style={-{Stealth[length=1.7mm]},line width=.55pt,draw=inkmuted}]
"""

ARCHITECTURE = STYLE + r"""
\node[box] (ui) at (0,0) {CLI / Web / Qt};
\node[box] (agent) at (0,-1.6) {Agent /\\ContextBuilder};
\node[box] (model) at (5,-1.6) {OllamaModel};
\node[box] (goals) at (-5,-1.6) {Goals / Scheduler};
\node[box] (control) at (-5,-3.2) {ControlStore / grants};
\node[box] (tools) at (0,-3.2) {ToolRegistry};
\node[box] (stores) at (5,-3.2) {Memory / Sessions};
\node[box] (purge) at (0,-4.8) {PurgeCoordinator};
\node[box] (knowledge) at (5,-4.8) {Knowledge /\\Evidence};
\draw[flow] (ui) -- (agent);
\draw[flow] (goals) -- (agent);
\draw[flow] (agent) -- (model);
\draw[flow] (control) -- (tools);
\draw[flow] (agent) -- (tools);
\draw[flow] (agent.south east) -- (stores.north west);
\draw[flow] (purge.north east) -- (stores.south west);
\draw[flow] (knowledge) -- (purge);
\end{tikzpicture}
"""

LIFECYCLE = STYLE + r"""
\node[box] (request) at (0,0) {Request / identity};
\node[box] (admit) at (5,0) {Evidence + admission};
\node[box] (model) at (10,0) {Generate / tool call};
\node[box] (auth) at (10,-1.8) {Validate / approval};
\node[box] (execute) at (5,-1.8) {Execute / result};
\node[box] (end) at (0,-1.8) {Terminal / commit};
\node[box] (resume) at (10,-3.6) {Resume / revalidate};
\draw[flow] (request) -- (admit);
\draw[flow] (admit) -- (model);
\draw[flow] (model) -- (auth);
\draw[flow] (auth) -- (execute);
\draw[flow] (execute) -- (end);
\draw[flow] (execute) -- (admit);
\draw[flow] (auth.south) -- node[left,font=\footnotesize] {wait} (resume.north);
\draw[flow] (resume.east) -- ++(.65,0) |- (auth.east);
\end{tikzpicture}
"""

PROVENANCE = STYLE + r"""
\node[box] (doc) at (0,0) {Document revision};
\node[box] (evidence) at (5,0) {Evidence ID};
\node[box] (memory) at (10,0) {Canonical memory};
\node[box] (change) at (0,-1.8) {Reindex / remove};
\node[box] (stale) at (5,-1.8) {Invalidate / stale};
\node[box] (goal) at (10,-1.8) {Pause dependent\\goal};
\node[box] (forget) at (0,-3.6) {Explicit forget};
\node[box] (purge) at (5,-3.6) {Transitive purge};
\node[box] (receipt) at (10,-3.6) {Store\\acknowledgments};
\draw[flow] (doc) -- (evidence);
\draw[flow] (evidence) -- (memory);
\draw[flow] (change) -- (stale);
\draw[flow] (stale.north east) -- (memory.south west);
\draw[flow] (stale) -- (goal);
\draw[flow] (forget) -- (purge);
\draw[flow] (purge) -- (receipt);
\end{tikzpicture}
"""

for name, source in {
    "architecture": ARCHITECTURE,
    "lifecycle": LIFECYCLE,
    "provenance": PROVENANCE,
}.items():
    # Scale only when needed; label sizes remain close to the manuscript small font.
    (FIG / f"{name}.tex").write_text(
        "% Generated by render_figures.py; edit the generator.\n"
        + r"\resizebox{\linewidth}{!}{%" + "\n" + source + "}\n"
    )

stats = json.loads((ROOT / "artifacts/historical-aggregates.json").read_text())
categories = stats["4096"]["by_category"]
order = ["ua", "en", "tools", "memory", "behavior", "adversarial", "conversation"]
passed, failed = [], []
for y, category in enumerate(order):
    counts = categories[category]
    passed.append(f"({counts['passed']},{y})")
    failed.append(f"({counts['runs']-counts['passed']},{y})")
plot = r"""% Generated from the historical aggregate; executions are correlated repeats.
\begin{tikzpicture}
\begin{axis}[
  width=.86\linewidth,height=6cm,xbar stacked,bar width=8pt,
  xmin=0,xmax=230,ymin=-.6,ymax=6.6,y dir=reverse,
  ytick={0,1,2,3,4,5,6},
  yticklabels={Ukrainian,English/code-switch,Tools,Memory,Behavior,Adversarial,Conversation},
  xlabel={Recorded executions (not independent cases)},
  tick label style={font=\small},label style={font=\small},
  axis line style={inkmuted},tick style={inkmuted},
  xmajorgrids,major grid style={gridline},
  legend style={font=\small,draw=none,at={(.98,.02)},anchor=south east},
  legend cell align=left]
"""
plot += r"\addplot[fill=series1!75,draw=series1] coordinates {" + " ".join(passed) + "};\n"
plot += r"\addplot[fill=series2!20,draw=series2,pattern=north east lines,pattern color=series2] coordinates {" + " ".join(failed) + "};\n"
plot += r"\legend{Passed,Failed}" + "\n" + r"\end{axis}\end{tikzpicture}" + "\n"
(FIG / "evaluation.tex").write_text(plot)
print("Generated four native LaTeX figures.")
